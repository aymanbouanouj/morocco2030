<?php

namespace Database\Seeders;

use App\Models\InterfaceTranslation;
use App\Models\Language;
use Illuminate\Database\Seeder;

class PublicInterfaceTranslationSeeder extends Seeder
{
    public function run(): void
    {
        $languages = Language::query()
            ->whereIn('code', ['ar', 'fr', 'es', 'it', 'pt', 'zh', 'hi', 'de', 'id'])
            ->get()
            ->keyBy('code');

        foreach ($this->translationSets() as $languageCode => $translations) {
            $language = $languages->get($languageCode);

            if (! $language) {
                continue;
            }

            $timestamp = now();

            InterfaceTranslation::query()->upsert(
                collect($translations)->map(fn (string $value, string $key) => [
                    'language_id' => $language->id,
                    'namespace' => 'public',
                    'group_name' => 'json',
                    'translation_key' => $key,
                    'value' => $value,
                    'created_at' => $timestamp,
                    'updated_at' => $timestamp,
                ])->values()->all(),
                ['language_id', 'namespace', 'group_name', 'translation_key'],
                ['value', 'updated_at']
            );
        }
    }

    protected function translationSets(): array
    {
        return [
            'ar' => $this->arabicTranslations(),
            'fr' => $this->frenchTranslations(),
            'es' => $this->expandedLanguageTranslations('es'),
            'it' => $this->expandedLanguageTranslations('it'),
            'pt' => $this->expandedLanguageTranslations('pt'),
            'zh' => $this->expandedLanguageTranslations('zh'),
            'hi' => $this->expandedLanguageTranslations('hi'),
            'de' => $this->expandedLanguageTranslations('de'),
            'id' => $this->expandedLanguageTranslations('id'),
        ];
    }

    protected function expandedLanguageTranslations(string $languageCode): array
    {
        return array_replace(
            $this->englishPublicKeyFallbacks(),
            $this->languageExpansionTranslations()[$languageCode] ?? []
        );
    }

    protected function englishPublicKeyFallbacks(): array
    {
        $keys = array_keys($this->frenchTranslations());

        return array_combine($keys, $keys);
    }

